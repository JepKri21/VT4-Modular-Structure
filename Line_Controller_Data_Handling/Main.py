from Client.AAS_Server_Client import AASServerClient
from Builders.Digital_Factory import DigitalFactory
from Builders.Asset_Builder import build_asset_from_shell

import json

from pprint import PrettyPrinter

pp = PrettyPrinter(
    width=200,      # max line width before wrapping
    compact=False,   # pack items onto fewer lines
    depth=None,     # limit nesting if you want (e.g., 3)
    sort_dicts=False,
    indent=2
)


def main():
    client = AASServerClient(port=5001)
    resources = []
    products = []

    shell_ids = client.get_all_shell_ids()

    for shell_id in shell_ids:
        shell_json = client.get_shell(shell_id)
        asset = build_asset_from_shell(shell_json, client)

        #We just check if the asset actually has any submodels before we add it
        if asset:
            if asset.is_resource():
                resources.append(asset)
            else:
                products.append(asset)

    print("Loaded resources:", len(resources))
    print("Loaded products:", len(products))
    print("=================================================================================================================================================================================")
    print("=========================================================Printing all Resources==================================================================================================")
    print("=================================================================================================================================================================================")

    for asset in resources:
        pp.pprint(asset.__dict__)
        print("=================================================================================================================================================================================")
        print("=================================================================================================================================================================================")
        print("=================================================================================================================================================================================")
               
    print("=================================================================================================================================================================================")
    print("=======================================================Printing all Products=====================================================================================================")
    print("=================================================================================================================================================================================")

    for asset in products:
        pp.pprint(asset.__dict__)
        print("=================================================================================================================================================================================")
        print("=================================================================================================================================================================================")
        print("=================================================================================================================================================================================")


if __name__ == "__main__":
    main()